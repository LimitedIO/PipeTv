package dev.limitedio.pipetv.ui

import dev.limitedio.pipetv.data.Prefs
import dev.limitedio.pipetv.i18n.K
import dev.limitedio.pipetv.i18n.S
import dev.limitedio.pipetv.media.Engine
import dev.limitedio.pipetv.media.Session
import dev.limitedio.pipetv.media.Sources
import dev.limitedio.pipetv.media.Subs
import dev.limitedio.pipetv.ui.widgets.*

/** Options panel shown over the video (Up key): quality and speed here, subtitles and audio language in pop-up menus. */
object PlayerMenu {
    private fun subLabel(i: Int) = Session.subs[i].displayLanguageName + if (Session.subs[i].isAutoGenerated) " (auto)" else ""

    fun rows(sub: SubMenu): List<Row> {
        val heights = Session.info?.let { Sources.heights(it) } ?: emptyList()
        return listOf(
            StepRow({ S.t(K.QUALITY) }, { "" }, { listOf(S.t(K.AUTO)) + heights.map { "${it}p" } },
                { if (Prefs.quality == 0) 0 else heights.indexOfFirst { it <= Prefs.quality } + 1 },
                { Prefs.quality = if (it == 0) 0 else heights[it - 1]; Session.reload() }),
            SliderRow({ S.t(K.SPEED) }, { "" }, 0.25f, 3f, 0.25f, { Prefs.speed }, { Prefs.speed = it; Engine.exo.setPlaybackSpeed(it) }, { "%.2fx".format(it) }),
            ActionRow({ S.t(K.SUBTITLES) }, { "" }, { if (Session.sub < 0) S.t(K.OFF) else if (Subs.state == 1) S.t(K.LOADING) else subLabel(Session.sub) }) {
                sub.choose(S.t(K.SUBTITLES), "", listOf(S.t(K.OFF)) + Session.subs.indices.map(::subLabel), Session.sub + 1) { Session.pickSubs(it - 1) }
            },
            ActionRow({ S.t(K.AUDIO_DUB) }, { "" }, { Session.audios.getOrNull(Session.audioIdx)?.label ?: "—" }) {
                if (Session.audios.size > 1) sub.choose(S.t(K.AUDIO_DUB), "", Session.audios.map { it.label }, Session.audioIdx) { Session.pickAudio(it) }
            },
        )
    }
}
